"""Само-проверка сборки перед публикацией.

Зачем. 04.08 дебиторка показала 92,7 млн вместо 1,6 млн, и ни одна автопроверка
не сработала: контроль выручки сходился, сверка была зелёной. Ошибку заметила Анна.
Вывод: одной контрольной цифры на один агрегат мало.

Как устроено. Две категории.
  • STOP  — цифрам верить нельзя. Сборка падает, публикации НЕ происходит,
            на сайте остаются вчерашние верные данные. Анна увидит это сама:
            через 20 часов без обновления дашборд вывесит жёлтый баннер.
  • NOTE  — не ошибка, просто событие (новый клиент, новая статья расходов).
            Публикуем, показываем строкой в баннере.

Принцип выбора проверок: ловим ТИХИЕ поломки — те, при которых всё зелёное,
а цифры врут. Громкие (нет доступа, нет файла) и так роняют сборку сами.
"""
import re

# --- пороги ---------------------------------------------------------------
DEBT_MAX_SHARE     = 0.25   # дебиторка больше четверти выручки — так не бывает
REV_DROP_TOL       = 0.005  # выручка накопительная за год: падение >0.5% невозможно
EBITDA_JUMP        = 0.15   # прыжок EBITDA за один прогон (обычно доли процента)
DEBT_JUMP_TIMES    = 3.0    # рост дебиторки в разы...
DEBT_JUMP_ABS      = 5_000_000   # ...и одновременно на такую сумму
SOURCE_STALE_DAYS  = 7           # столько дней без новых строк в источнике — уже вопрос
ZERO_COLLAPSE_MIN  = 100_000     # был заметной цифрой, стал ровно 0 — так не бывает
MONEY_EPS          = 1.0    # копеечные расхождения от округлений не считаем


def _norm(name):
    """Имя объекта без года и пометок: «ООО ЗетТЕК (25) стар» и «ООО ЗетТЕК (26)»
    должны схлопнуться в одно и подсветиться как дубль."""
    s = str(name).lower()
    s = re.sub(r"\(\s*\d{2}\s*\)", "", s)          # (25), (26)
    s = re.sub(r"\b(стар|старый|архив|копия)\b", "", s)
    return re.sub(r"[^a-zа-яё0-9]", "", s)


def _row_total(row):
    return sum((row or {}).get("months", {}).values())


def run(data, prev=None):
    """Вернуть (stops, notes). prev — метрики прошлой опубликованной сборки или None."""
    stops, notes = [], []
    S, N = stops.append, notes.append
    p = data["pnl_all"]
    rev = _row_total(p["revenue"])
    debt = sum(r.get("долг", 0) for r in data["receivables"])

    # 1. Контроль янв–июн (был и раньше, теперь блокирует публикацию)
    if not data.get("reconciled"):
        S(f"Контроль выручки янв–июн не сошёлся (должно быть {data['control_revenue']:,} ₽).")

    # 2. Вообще не нашли клиентов — структура таблицы уехала
    if not data.get("known_clients"):
        S("В таблице не найдено ни одного листа-клиента.")

    # 3. Дубли объектов. Ровно этим был баг 04.08: два «ООО ЗетТЕК», один из них архив 2025.
    seen = {}
    for o in data["known_clients"]:
        seen.setdefault(_norm(o), []).append(o)
    for _, names in seen.items():
        if len(names) > 1:
            S(f"Один клиент попал в расчёт дважды: {', '.join(names)}. "
              f"Похоже, подхватился архивный лист прошлого года.")

    # 4. Дебиторка построчно: нельзя быть должным больше, чем тебе оказали услуг
    for r in data["receivables"]:
        d, o = r.get("долг", 0), r.get("оказано", 0)
        if d > o * 1.02 + 1000:
            S(f"«{r['obj']}»: долг {d:,.0f} ₽ больше оказанных услуг {o:,.0f} ₽.")
        if d < -1000:
            S(f"«{r['obj']}»: отрицательный долг {d:,.0f} ₽.")

    # 5. Дебиторка как доля выручки. Поймала бы 04.08: 92,7 млн при выручке 158 млн = 59%.
    if rev > 0 and debt > rev * DEBT_MAX_SHARE:
        S(f"Дебиторка {debt:,.0f} ₽ — это {debt/rev:.0%} выручки. Больше {DEBT_MAX_SHARE:.0%} не бывает.")

    # 6. Части равны целому: выручка по объектам за янв–июн = контрольная цифра
    by_obj = sum(r["total"] for r in data["revenue_by_object"])
    if abs(by_obj - data["control_revenue"]) > MONEY_EPS:
        S(f"Сумма выручки по объектам {by_obj:,.0f} ₽ не сходится с контролем "
          f"{data['control_revenue']:,} ₽.")

    # 7. Сумма по ИП = общая выручка
    ips = sum(_row_total(data["pnl"][ip]["revenue"]) for ip in ("Миронов", "Молчанов"))
    if abs(ips - rev) > MONEY_EPS:
        S(f"Выручка по ИП ({ips:,.0f} ₽) не сходится с общей ({rev:,.0f} ₽) — "
          f"часть объектов потеряла принадлежность к ИП.")

    # 8. Арифметика P&L: строки должны складываться в итоги
    if abs((rev - p["variable_total"]) - p["margin"]) > MONEY_EPS:
        S("P&L не сходится: выручка минус переменные расходы не равна марже.")
    if abs((p["margin"] - p["fixed_total"]) - p["ebitda"]) > MONEY_EPS:
        S("P&L не сходится: маржа минус постоянные расходы не равна EBITDA.")
    if abs((p["ebitda"] - _row_total(p["tax"])) - p["net"]) > MONEY_EPS:
        S("P&L не сходится: EBITDA минус налоги не равна чистой прибыли.")

    # 9. Сравнение с прошлой опубликованной сборкой — главный ловец тихих поломок
    if prev:
        pr, pd_ = prev.get("revenue", 0), prev.get("debt", 0)
        pe, po = prev.get("ebitda", 0), prev.get("objects", 0)
        if pr > 0 and rev < pr * (1 - REV_DROP_TOL):
            S(f"Выручка упала с {pr:,.0f} до {rev:,.0f} ₽. Накопительная выручка за год "
              f"уменьшаться не может — похоже, часть данных перестала читаться.")
        if po and len(data["known_clients"]) < po:
            S(f"Клиентов стало меньше: было {po}, стало {len(data['known_clients'])}. "
              f"Лист могли переименовать или удалить.")
        if pe and abs(pe) > 1 and abs(ebitda_delta := (p["ebitda"] - pe) / abs(pe)) > EBITDA_JUMP:
            S(f"EBITDA изменилась на {ebitda_delta:+.0%} за один прогон "
              f"({pe:,.0f} → {p['ebitda']:,.0f} ₽). Так быстро не бывает.")
        if pd_ > 0 and debt > pd_ * DEBT_JUMP_TIMES and (debt - pd_) > DEBT_JUMP_ABS:
            S(f"Дебиторка выросла с {pd_:,.0f} до {debt:,.0f} ₽ за один прогон.")
        # ВНЕЗАПНЫЙ НОЛЬ. Так выглядит переименованный столбец: цифра была, стала ровно 0,
        # и больше нигде ничего не ломается. Единственный способ это заметить — сравнение.
        for key, now_v, name in (("revenue", rev, "выручка"),
                                 ("debt", debt, "дебиторка"),
                                 ("ebitda", p["ebitda"], "EBITDA")):
            was = prev.get(key, 0)
            if abs(was) > ZERO_COLLAPSE_MIN and now_v == 0:
                S(f"Показатель «{name}» стал ровно нулём, а в прошлой сборке был {was:,.0f} ₽. "
                  f"Обычно так выглядит переименованный столбец в исходнике.")

    # Свежесть исходника. Ловит случай «таблицу пересоздали, робот читает замороженную
    # копию»: сборка идёт, метка обновляется, а данные в ней замерли. Не STOP — бывают
    # праздники и простои, но на дашборде это должно быть видно.
    stale = data.get("source_stale_days")
    if stale is not None and stale > SOURCE_STALE_DAYS:
        N(f"В таблице-источнике нет новых строк уже {stale} дн. "
          f"Либо простой в работе, либо робот читает не тот файл.")

    # --- NOTE: события, а не ошибки (по решению Анны 04.08) -----------------
    for w in data.get("warnings", []):
        N(w)

    return stops, notes


def metrics(data):
    """Слепок ключевых цифр — его публикуем рядом с дашбордом, следующая сборка
    скачает его и сравнит с собой. Так ловится скачок между прогонами."""
    p = data["pnl_all"]
    return {
        "updated_at": data["updated_at"],
        "revenue": _row_total(p["revenue"]),
        "margin": p["margin"],
        "ebitda": p["ebitda"],
        "net": p["net"],
        "debt": sum(r.get("долг", 0) for r in data["receivables"]),
        "objects": len(data.get("known_clients", [])),
    }
